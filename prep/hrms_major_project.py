def _extract_json(text):
    # Robust extraction: find the outermost curly braces to ignore conversational text before or after
    a, b = text.find("{"), text.rfind("}")
    if a == -1 or b == -1:
        raise ValueError("no JSON object in reply")
    cleaned = text[a:b + 1]
    return json.loads(cleaned)

def llm_json(system, user, model_cls, retries=1):
    err = ""
    for _ in range(retries + 1):
        raw = llm(system, user + (f"\n\nYour previous reply was invalid ({err}). Return ONLY valid JSON." if err else ""))
        try:
            return model_cls.model_validate(_extract_json(raw))
        except Exception as e:                    # covers JSONDecodeError and pydantic ValidationError
            err = str(e)[:300]
    raise RuntimeError(f"LLM output failed validation: {err}")

