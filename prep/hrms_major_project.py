# ---------- Node: ingest ----------
def node_ingest(jd, resume, transcript, candidate_name=""):
    if not all(x and x.strip() for x in (jd, resume, transcript)):
        raise ValueError("jd, resume and transcript are all required")
    if len(jd) + len(resume) + len(transcript) > MAX_CHARS:
        raise ValueError(f"Input exceeds {MAX_CHARS} chars; truncate or chunk it")
    warnings = [f"possible prompt injection: '{m.group(0)}'" for m in INJECTION.finditer(resume + transcript)]
    d = Dossier(jd=jd.strip(), resume=redact(resume, candidate_name),
                turns=parse_transcript(redact(transcript, candidate_name)), warnings=warnings)
    out = llm_json(CLAIM_SYS, f"<resume>\n{d.resume}\n</resume>", ClaimList)
    kept = []
    for c in out.claims[:8]:
        if norm(c.resume_quote) in norm(d.resume):
            kept.append(c)
        else:
            d.warnings.append(f"dropped claim '{c.text[:40]}': quote not found verbatim in resume")
    for i, c in enumerate(kept, 1):
        c.id = f"C{i}"
    if not kept:
        d.warnings.append("no verifiable claims extracted")
    d.claims = kept
    return d

