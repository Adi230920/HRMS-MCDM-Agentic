# ---------- Text utilities ----------
_T = str.maketrans({"’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-"})
def norm(s):
    return re.sub(r"\s+", " ", s.translate(_T)).strip().lower()

PII = [
    (r"[\w.+-]+@[\w-]+\.[\w.-]+", "[EMAIL]"),
    (r"(?<!\w)(?:\+?\d{1,3}[\s.-]?)?(?:\(?\d{3}\)?[\s.-]?\d{3}[\s.-]?\d{4}|\d{5}[\s-]?\d{5})(?!\w)", "[PHONE]"),
    (r"(?i)https?://\S+|\b(?:www\.|linkedin\.com|github\.com)\S*", "[URL]"),
    (r"(?i)\b(?:aged?|dob|born(?: in)?)\b\W{0,3}\d{1,4}(?:[/-]\d{1,4}){0,2}", "[AGE]"),
    (r"(?i)\b(?:he|she)\b", "they"),
    (r"(?i)\b(?:his|hers|her)\b", "their"),
    (r"(?i)\bhim\b", "them"),
    (r"(?i)\b(?:mr|mrs|ms|miss)\.?(?=\s)", ""),
]

def redact(text, name=""):
    for pat, rep in PII:
        text = re.sub(pat, rep, text)
    for tok in {t for t in name.split() if len(t) > 1}:
        text = re.sub(rf"\b{re.escape(tok)}\b", "[CANDIDATE]", text, flags=re.I)
    return text

TURN_RE = re.compile(r"^\s*(INTERVIEWER|CANDIDATE|INTERVIEWEE)\s*:\s*", re.I | re.M)

def parse_transcript(raw):
    parts = TURN_RE.split(raw)                     # ['', 'Interviewer', 'text', 'Candidate', 'text', ...]
    if len(parts) < 3:
        raise ValueError("Transcript needs 'Interviewer:' / 'Candidate:' speaker labels")
    turns = []
    for i in range(1, len(parts), 2):
        spk = "CANDIDATE" if parts[i].upper() in ("CANDIDATE", "INTERVIEWEE") else "INTERVIEWER"
        turns.append(Turn(id=f"T{len(turns) + 1}", speaker=spk, text=parts[i + 1].strip()))
    if not any(t.speaker == "CANDIDATE" for t in turns):
        raise ValueError("No candidate turns found in transcript")
    return turns

INJECTION = re.compile(r"(?i)ignore (?:all |any )?(?:previous|prior|above)|system prompt|you are now|disregard .{0,30}instructions|rate (?:this|the) candidate")

