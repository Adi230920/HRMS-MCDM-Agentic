# ---------- Deterministic citation enforcement ----------
def verify(ev, d):
    q = norm(re.sub(r"^\s*(\[T\d+\]\s*)?(CANDIDATE:\s*)?", "", ev.quote, flags=re.I))
    if len(q) < 8:
        return False
    hay = norm(d.resume) if ev.source == "resume" else norm(" ".join(t.text for t in d.turns if t.speaker == "CANDIDATE"))
    return q in hay

def enforce_citations(ev, d):
    for r in ev.ratings:
        for e in r.evidence: e.verified = verify(e, d)
        ok_any = any(e.verified for e in r.evidence)
        ok_tr = any(e.verified and e.source == "transcript" for e in r.evidence)
        new = r.rating
        if r.rating == "STRONG" and not ok_tr:
            new = "PARTIAL" if ok_any else "NOT_DEMONSTRATED"
        elif r.rating == "PARTIAL" and not ok_any:
            new = "NOT_DEMONSTRATED"
        if new != r.rating:
            ev.violations.append(f"{r.criterion}: {r.rating} -> {new} (no verified quote)")
            r.rating = new
    for f in ev.claim_findings:
        for e in f.evidence: e.verified = verify(e, d)
        if f.status != "UNVERIFIED" and not any(e.verified and e.source == "transcript" for e in f.evidence):
            ev.violations.append(f"{f.claim_id}: {f.status} -> UNVERIFIED (no verified transcript quote)")
            f.status = "UNVERIFIED"
    return ev

def run_agent(name, d):
    cfg = AGENTS[name]
    system = SHARED.format(persona=cfg["persona"], focus=cfg["focus"], criteria=", ".join(cfg["criteria"])) + SCHEMA_HINT
    ev = llm_json(system, build_user(d), AgentEval)
    ev.agent = name
    have = {r.criterion: r for r in ev.ratings if r.criterion in cfg["criteria"]}
    ev.ratings = [have[c] if c in have else CriterionRating(criterion=c, rating="NOT_DEMONSTRATED") for c in cfg["criteria"]]
    known = {c.id for c in d.claims}
    ev.claim_findings = [f for f in ev.claim_findings if f.claim_id in known]
    return enforce_citations(ev, d)

# ---------- Node: parallel agents ----------
def node_agents(d):
    evals, failed = {}, {}
    def _one(n):
        try:
            return n, run_agent(n, d), None
        except Exception as e:
            return n, None, str(e)[:200]
    with ThreadPoolExecutor(max_workers=3) as ex:
        for n, ev, err in ex.map(_one, AGENTS):
            if ev: evals[n] = ev
            else: failed[n] = err
    if not evals:
        raise RuntimeError(f"All agents failed: {failed}")
    return evals, failed

